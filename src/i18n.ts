const translations: Record<Language, TranslationTable> = { en, zh };

export function initialLanguage(): Language {
  const stored = window.localStorage.getItem("amr-language");
  if (stored === "zh" || stored === "en") {
    return stored;
  }
  return window.navigator.language.toLowerCase().startsWith("zh") ? "zh" : "en";
}

export function setStoredLanguage(language: Language) {
  window.localStorage.setItem("amr-language", language);
  document.documentElement.lang = language === "zh" ? "zh-CN" : "en";
}

export function translator(language: Language) {
  return (key: TranslationKey, values: Record<string, string | number> = {}) =>
    Object.entries(values).reduce(
      (text, [name, value]) => text.replaceAll(`{${name}}`, String(value)),
      translations[language][key],
    );
}

export type Translate = ReturnType<typeof translator>;
