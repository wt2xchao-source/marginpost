import { createHash } from "node:crypto";
import { execFileSync } from "node:child_process";
import { readdir, readFile, writeFile } from "node:fs/promises";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const repoRoot = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const outputPath = join(repoRoot, "THIRD_PARTY_LICENSES.txt");
const licenseFilePattern =
  /^(license|licence|copying|copyright)([-._].*)?$/i;

async function readJson(path) {
  return JSON.parse(await readFile(path, "utf8"));
}

function repositoryUrl(repository) {
  if (typeof repository === "string") {
    return repository;
  }

  return repository?.url ?? "";
}

function normalizeText(content) {
  return content
    .replace(/\r\n?/g, "\n")
    .split("\n")
    .map((line) => line.replace(/[ \t]+$/u, ""))
    .join("\n")
    .trim();
}

async function findLicenseFiles(packageRoot, explicitPath = "") {
  const candidates = new Set();

  if (explicitPath) {
    candidates.add(resolve(packageRoot, explicitPath));
  }

  for (const name of await readdir(packageRoot)) {
    if (licenseFilePattern.test(name)) {
      candidates.add(join(packageRoot, name));
    }
  }

  const files = [];
  for (const path of [...candidates].sort()) {
    const content = normalizeText(await readFile(path, "utf8"));
    if (content) {
      files.push({ name: path.slice(packageRoot.length + 1), content });
    }
  }

  return files;
}

async function npmPackages() {
  const lock = await readJson(join(repoRoot, "package-lock.json"));
  const packages = [];

  for (const [relativePath, lockEntry] of Object.entries(lock.packages ?? {})) {
    if (!relativePath.startsWith("node_modules/") || lockEntry.dev === true) {
      continue;
    }

    const packageRoot = join(repoRoot, relativePath);
    const manifest = await readJson(join(packageRoot, "package.json"));
    packages.push({
      ecosystem: "npm",
      name: manifest.name,
      version: manifest.version,
      license: manifest.license ?? lockEntry.license ?? "UNKNOWN",
      source: repositoryUrl(manifest.repository),
      files: await findLicenseFiles(packageRoot),
    });
  }

  return packages;
}

function cargoLicenses() {
  const cargo = process.env.CARGO ?? "cargo";
  return normalizeText(
    execFileSync(
      cargo,
      [
        "about",
        "generate",
        "--manifest-path",
        join(repoRoot, "src-tauri", "Cargo.toml"),
        join(repoRoot, "about.hbs"),
      ],
      {
        cwd: repoRoot,
        encoding: "utf8",
        maxBuffer: 64 * 1024 * 1024,
      },
    ),
  );
}

function renderNpm(packages) {
  const sorted = packages.sort((left, right) =>
    `${left.ecosystem}:${left.name}@${left.version}`.localeCompare(
      `${right.ecosystem}:${right.name}@${right.version}`,
    ),
  );
  const texts = new Map();
  const missing = [];

  for (const entry of sorted) {
    if (entry.files.length === 0) {
      missing.push(`${entry.ecosystem}:${entry.name}@${entry.version}`);
    }

    for (const file of entry.files) {
      const id = createHash("sha256")
        .update(file.content)
        .digest("hex")
        .slice(0, 12);
      const current = texts.get(id) ?? {
        content: file.content,
        packages: [],
      };
      current.packages.push(
        `${entry.ecosystem}:${entry.name}@${entry.version} (${file.name})`,
      );
      texts.set(id, current);
      file.textId = id;
    }
  }

  if (missing.length > 0) {
    throw new Error(
      `Missing bundled license text for ${missing.length} package(s):\n${missing.join("\n")}`,
    );
  }

  const lines = [
    "MARGINPOST THIRD-PARTY SOFTWARE LICENSES",
    "",
    "Generated from package-lock.json and src-tauri/Cargo.lock.",
    "Do not edit this file manually; run `npm run licenses:generate`.",
    "",
    "PACKAGE INDEX",
    "=============",
    "",
  ];

  for (const entry of sorted) {
    lines.push(
      `[${entry.ecosystem}] ${entry.name}@${entry.version}`,
      `Declared license: ${entry.license}`,
      `Source: ${entry.source || "not declared"}`,
      `License text: ${entry.files.map((file) => `${file.textId} (${file.name})`).join(", ")}`,
      "",
    );
  }

  lines.push("LICENSE TEXTS", "=============", "");

  for (const [id, text] of [...texts.entries()].sort(([left], [right]) =>
    left.localeCompare(right),
  )) {
    lines.push(
      `--- ${id} ---`,
      `Applies to: ${text.packages.sort().join("; ")}`,
      "",
      text.content,
      "",
    );
  }

  return `${lines.join("\n")}\n`;
}

const packages = await npmPackages();
const content = [
  renderNpm(packages),
  "",
  cargoLicenses().trim(),
  "",
].join("\n");
await writeFile(outputPath, content, "utf8");
console.log(
  `Generated ${outputPath} for ${packages.length} npm packages and the locked Cargo graph.`,
);
